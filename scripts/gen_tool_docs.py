"""Write knowledge/Projects/AutoCAD-MCP/Tool reference.md from the live tool registry.

    python scripts/gen_tool_docs.py          # rewrite the page
    python scripts/gen_tool_docs.py --check  # exit 1 if the page is out of date (used by CI)
"""

from __future__ import annotations

import asyncio
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

from autocad_mcp.server import mcp  # noqa: E402

PAGE = os.path.join(ROOT, "knowledge", "Projects", "AutoCAD-MCP", "Tool reference.md")
GROUPS = {
    "documents": "Session and drawings", "query": "Inspect", "layers": "Layers", "draw": "Draw",
    "annotate": "Dimensions and leaders", "blocks": "Blocks", "edit": "Edit", "plot": "Plot",
    "settings": "Drawing settings", "sheets": "Sheets and viewports",
    "power": "Command line (opt-in)",
}


def _module_of(tool) -> str:
    fn = getattr(tool, "fn", None)
    module = getattr(getattr(fn, "__wrapped__", fn), "__module__", "") or ""
    return module.rsplit(".", 1)[-1]


def render() -> str:
    tools = asyncio.run(mcp.list_tools())
    registry = {t.name: t for t in mcp._tool_manager.list_tools()} if hasattr(mcp, "_tool_manager") else {}
    by_group: dict[str, list] = {}
    for t in tools:
        group = _module_of(registry[t.name]) if t.name in registry else "other"
        by_group.setdefault(group, []).append(t)
    lines = [
        "# Tool reference",
        "",
        "Generated by `scripts/gen_tool_docs.py` from the server's tool registry; do not edit by hand.",
        f"Tools: **{len(tools)}**. Read-only tools are marked (read-only). Lengths are drawing units, angles degrees.",
        "",
        "See [[Projects/AutoCAD-MCP/index]] for status and [[Research/AutoCAD API gotchas]] for API lessons.",
        "",
    ]
    order = list(GROUPS) + sorted(set(by_group) - set(GROUPS))
    for group in order:
        if group not in by_group:
            continue
        lines += [f"## {GROUPS.get(group, group)}", ""]
        for t in by_group[group]:
            ro = " (read-only)" if t.annotations and t.annotations.read_only_hint else ""
            summary = " ".join((t.description or "").strip().split("\n\n")[0].split())
            params = ", ".join(f"`{p}`" for p in (t.input_schema or {}).get("properties", {}))
            lines.append(f"- **`{t.name}`**{ro}: {summary}" + (f" Parameters: {params}." if params else ""))
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def main() -> int:
    text = render()
    if "--check" in sys.argv:
        current = open(PAGE, encoding="utf-8").read() if os.path.exists(PAGE) else ""
        if current != text:
            print(f"{PAGE} is out of date; run python scripts/gen_tool_docs.py")
            return 1
        print("Tool reference is up to date.")
        return 0
    os.makedirs(os.path.dirname(PAGE), exist_ok=True)
    with open(PAGE, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    print(f"Wrote {PAGE}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
